// Writes reference/components.md and reference/blocks.md from the app's own registries,
// so the docs list exactly what the UI Kit and the Blocks gallery show.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const demo = (process.env.DOCS_DEMO_URL ?? 'http://localhost:5173').replace(/\/$/, '');
const read = (p) => readFileSync(join(root, p), 'utf8');
const field = (block, name) => {
  const m = new RegExp(`${name}:\\s*\\n?\\s*'((?:[^'\\\\]|\\\\.)*)'`).exec(block);
  return m ? m[1].replace(/\\'/g, "'") : '';
};
const esc = (s) => s.replace(/\|/g, '\\|');

// Components
const reg = read('src/showcase/registry.ts');
const groups = [...reg.match(/export const GROUPS = \[([\s\S]*?)\] as const/)[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
const meta = reg.slice(reg.indexOf('const META'), reg.indexOf('];', reg.indexOf('const META')));
const comps = [...meta.matchAll(/\{([\s\S]*?)\n  \}/g)].map((m) => ({
  slug: field(m[1], 'slug'),
  name: field(m[1], 'name'),
  group: field(m[1], 'group'),
  status: field(m[1], 'status'),
  description: field(m[1], 'description'),
}));
const charts = new Set(comps.filter((c) => c.group === 'Charts').map((c) => c.name));
let out = `# Components

${comps.length} components in ${groups.length} groups. Each has a live page in the app's UI Kit (\`/ui\`) with a playground, examples you can view in dark mode, right-to-left and at phone width, the exact code, keyboard and accessibility notes, and a props table.

\`\`\`tsx
import { Button, DataTable, Modal } from '@/components/kit';
import { AreaChart, DonutChart } from '@/components/charts'; // charts load only where used
\`\`\`

<!-- Generated by docs/scripts/gen-components.mjs from src/showcase/registry.ts. Don't edit by hand. -->
`;
for (const g of groups) {
  const list = comps.filter((c) => c.group === g);
  if (!list.length) continue;
  out += `\n## ${g}\n\n| Component | What it's for | |\n|---|---|---|\n`;
  for (const c of list) out += `| **${c.name}** | ${esc(c.description)} | [Live](${demo}/ui/${c.slug}) |\n`;
}
out += `\nCharts (${[...charts].join(', ')}) import from \`@/components/charts\`; everything else from \`@/components/kit\`.\n`;
writeFileSync(join(root, 'docs/reference/components.md'), out);

// Blocks
const breg = read('src/blocks/registry.ts');
const bsrc = breg.slice(breg.indexOf('const META'), breg.indexOf('];', breg.indexOf('const META')));
const bmeta = [...bsrc.matchAll(/\{([^{}]*file:[^{}]*)\}/g)].map((m) => [null, field(m[1], 'file'), field(m[1], 'name'), field(m[1], 'category'), field(m[1], 'description')]);
const cats = [...breg.match(/BLOCK_CATEGORIES = \[([\s\S]*?)\] as const/)[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
let bout = `# Blocks

${bmeta.length} ready-made sections, each a single file in \`src/blocks\`. Browse them live at \`/ui/blocks\`, open the Code tab, and copy the file into your page. Sample numbers come from \`src/blocks/_data.ts\`; replace them with your queries.

<!-- Generated by docs/scripts/gen-components.mjs from src/blocks/registry.ts. Don't edit by hand. -->
`;
for (const c of cats) {
  bout += `\n## ${c}\n\n| Block | What it shows | File |\n|---|---|---|\n`;
  for (const [, file, name, cat, desc] of bmeta) if (cat === c) bout += `| **${name}** | ${esc(desc)} | \`src/blocks/${file}.tsx\` |\n`;
}
writeFileSync(join(root, 'docs/reference/blocks.md'), bout);
console.log(`docs: ${comps.length} components, ${bmeta.length} blocks`);
